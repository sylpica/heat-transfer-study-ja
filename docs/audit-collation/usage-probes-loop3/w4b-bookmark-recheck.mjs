// W4b 再測定：ブックマークのリロード保持（localStorage 実測＋検索後の行で再確認）
import {launch,newPage,DIST,makeLog} from './lib.mjs';
const log=makeLog('W4b');
const browser=await launch();
const {ctx,page,errors}=await newPage(browser,{width:375});
page.setDefaultTimeout(120000);
await page.goto(DIST+'/index.html#glossary',{waitUntil:'load'});
await page.waitForTimeout(1800);
await page.locator('#glossary-query').fill('フィン効率');
await page.waitForTimeout(1200);
const before=await page.evaluate(()=>{const row=document.querySelector('#term-fin-efficiency');const b=row?[...row.querySelectorAll('button')].find(x=>/☆|★/.test(x.textContent)):null;return b?b.textContent.trim():null;});
log.info('ブックマーク前: '+before);
await page.evaluate(()=>{const row=document.querySelector('#term-fin-efficiency');const b=row?[...row.querySelectorAll('button')].find(x=>/☆|★/.test(x.textContent)):null;b?.click();});
await page.waitForTimeout(600);
const lsKeys=await page.evaluate(()=>Object.keys(localStorage));
log.info('localStorage keys: '+JSON.stringify(lsKeys));
const snap1=await page.evaluate(()=>{const out={};for(const k of Object.keys(localStorage)){const v=localStorage.getItem(k);if(v&&v.includes('fin-efficiency'))out[k]='contains fin-efficiency ('+v.length+' bytes)';}return out;});
log.info('保存スナップショット（fin-efficiency を含むキー）: '+JSON.stringify(snap1));
await page.reload({waitUntil:'load'});
await page.waitForTimeout(2200);
const snap2=await page.evaluate(()=>{const out={};for(const k of Object.keys(localStorage)){const v=localStorage.getItem(k);if(v&&v.includes('fin-efficiency'))out[k]='contains fin-efficiency ('+v.length+' bytes)';}return out;});
log.info('リロード後スナップショット: '+JSON.stringify(snap2));
await page.goto(DIST+'/index.html#glossary',{waitUntil:'load'});
await page.waitForTimeout(1500);
const rowNoSearch=await page.evaluate(()=>({exists:!!document.querySelector('#term-fin-efficiency'),rows:document.querySelectorAll('[id^="term-"]').length}));
log.info('リロード後・検索なしの行: '+JSON.stringify(rowNoSearch));
await page.locator('#glossary-query').fill('フィン効率');
await page.waitForTimeout(1200);
const afterSearch=await page.evaluate(()=>{const row=document.querySelector('#term-fin-efficiency');const b=row?[...row.querySelectorAll('button')].find(x=>/☆|★/.test(x.textContent)):null;return {row:!!row,btn:b?b.textContent.trim():null};});
log.info('リロード後・検索後の行: '+JSON.stringify(afterSearch));
if(afterSearch.btn&&afterSearch.btn.includes('★'))log.ok('リロード後もブックマークは保持されている（検索後の行で ★ を確認）');
else log.fail('リロード後にブックマークが保持されていない（localStorage: '+JSON.stringify(snap2)+'）');
log.info('W4b errors: '+JSON.stringify(errors));
await ctx.close();
await browser.close();
console.log('W4b DONE');
