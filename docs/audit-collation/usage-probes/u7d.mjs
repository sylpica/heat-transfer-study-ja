import {launch,newPage,DIST,makeLog} from './lib.mjs';
const log=makeLog('U7d');
const browser=await launch();
const {ctx,page}=await newPage(browser,{width:375});
await page.goto(DIST+'/dynamic/index.html',{waitUntil:'networkidle'});
await page.waitForTimeout(1300);
const pressed=()=>page.evaluate(()=>document.querySelector('.sim-guide-toggle')?.getAttribute('aria-pressed'));
log.info('初期 aria-pressed='+await pressed());
await page.evaluate(()=>{document.querySelector('.sim-guide-toggle')?.click();});
await page.waitForTimeout(500);
log.info('ON後 aria-pressed='+await pressed());
await page.keyboard.press('Escape');
await page.waitForTimeout(400);
log.info('Esc後 aria-pressed='+await pressed());
await page.reload({waitUntil:'networkidle'});
await page.waitForTimeout(1200);
log.info('リロード後 aria-pressed='+await pressed());
if((await pressed())==='false')log.ok('ガイドOFF状態がリロード後も保持される（localStorage）');
await ctx.close();await browser.close();
