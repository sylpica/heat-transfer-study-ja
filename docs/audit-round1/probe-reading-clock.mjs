import {createRequire} from 'node:module';
import {startServer} from './scripts/serve.mjs';
const require=createRequire(import.meta.url);
const {chromium}=require('playwright');
const server=await startServer({port:0}),base=`http://127.0.0.1:${server.address().port}`;
const browser=await chromium.launch({headless:true,timeout:20000});
const ctx=await browser.newContext({viewport:{width:390,height:844},colorScheme:'dark',timezoneId:'Asia/Tokyo'});
const page=await ctx.newPage();page.setDefaultTimeout(60000);
page.on('pageerror',e=>console.log('PAGEERROR',e.message));
await page.clock.install({time:new Date('2026-10-20T03:00:00Z')});
await page.goto(`${base}/#reader`);
await page.locator('.reader-title').waitFor();
await page.locator('.reader-toc details').filter({has:page.locator('[data-section="8.2"]')}).locator('summary').click();
await page.locator('.reader-toc [data-section="8.2"]').click();
await page.locator('.reader-title').waitFor();
console.log('title:',await page.locator('.reader-title').innerText());
console.log('visibilityState:',await page.evaluate(()=>document.visibilityState),'hasFocus:',await page.evaluate(()=>document.hasFocus()));
await page.clock.runFor(10000);
const timed=await page.evaluate(()=>JSON.parse(localStorage.getItem('heat-study-ja:v1')));
console.log('activities:',JSON.stringify(timed.activities));
console.log('visibilityState after:',await page.evaluate(()=>document.visibilityState),'hasFocus:',await page.evaluate(()=>document.hasFocus()));
await browser.close();server.close();
